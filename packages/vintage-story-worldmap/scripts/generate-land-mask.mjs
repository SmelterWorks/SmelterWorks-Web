// One-off generator. Rasterizes real coastlines (world-atlas land-50m) into a
// compact 1-degree land/water bitmap consumed by src/terrain.js.
//
// Containment uses d3-geo's geoContains, which does true spherical polygon
// containment (great-circle winding), not a planar ray cast. A planar ray cast
// on raw lng/lat is unreliable near the poles and across the antimeridian,
// where a single ray in the +longitude direction can cross a coastline an
// unpredictable number of times. That previously misclassified most of the
// Arctic Ocean as land. geoContains has no such failure mode.
//
// Run with: node scripts/generate-land-mask.mjs (takes a few minutes; this is
// a build-time asset, not something run on every install or build).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, '../src/land-mask-data.js');
const landTopoPath = resolve(__dirname, '../node_modules/world-atlas/land-50m.json');

const WIDTH = 360;
const HEIGHT = 180;

const topology = JSON.parse(readFileSync(landTopoPath, 'utf8'));
// world-atlas ships "land" as a GeometryCollection with a single merged
// MultiPolygon feature. topojson-client.feature() always wraps that in a
// FeatureCollection; geoContains needs the single Feature (or its geometry)
// inside it, not the collection itself.
const land = feature(topology, topology.objects.land).features[0];

function isLand(lng, lat) {
    return geoContains(land, [lng, lat]);
}

const bits = new Uint8Array(WIDTH * HEIGHT);
const startedAt = Date.now();

for (let row = 0; row < HEIGHT; row++) {
    const lat = 90 - (row + 0.5) * (180 / HEIGHT);

    for (let col = 0; col < WIDTH; col++) {
        const lng = -180 + (col + 0.5) * (360 / WIDTH);
        bits[row * WIDTH + col] = isLand(lng, lat) ? 1 : 0;
    }

    if (row % 30 === 0 || row === HEIGHT - 1) {
        const elapsedSeconds = ((Date.now() - startedAt) / 1000).toFixed(1);
        console.log(`Row ${row + 1}/${HEIGHT} (${elapsedSeconds}s elapsed)`);
    }
}

let binary = '';

for (let i = 0; i < bits.length; i += 8) {
    let byte = 0;

    for (let bit = 0; bit < 8; bit++) {
        byte = (byte << 1) | (bits[i + bit] || 0);
    }

    binary += String.fromCharCode(byte);
}

const encoded = Buffer.from(binary, 'binary').toString('base64');

const contents = `// Generated by scripts/generate-land-mask.mjs. Do not edit by hand.
// 1-degree land/water bitmap rasterized from world-atlas land-50m coastlines.
export const MASK_WIDTH = ${WIDTH};
export const MASK_HEIGHT = ${HEIGHT};
export const LAND_MASK_BASE64 =
    '${encoded}';
`;

writeFileSync(outputPath, contents);

console.log(`Wrote ${outputPath} (${WIDTH}x${HEIGHT}, ${encoded.length} base64 chars)`);
