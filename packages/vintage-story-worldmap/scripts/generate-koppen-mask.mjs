// One-off generator. Downsamples Beck et al. (2018) Köppen-Geiger present-day
// classification (0.5° land cells) into a compact 1-degree uint8 raster for
// src/terrain.js. Source CSV is the land-only 0.5° grid published alongside
// koppen-climate-lookup (derived from Beck_KG_V1_present_0p5.tif).
//
// Run with: node scripts/generate-koppen-mask.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, '../src/koppen-mask-data.js');

const WIDTH = 360;
const HEIGHT = 180;

// Numeric indices stored in the raster. Index 0 means ocean or no CSV sample.
export const KOPPEN_CLASSES = [
    'Af',
    'Am',
    'As',
    'Aw',
    'BSh',
    'BSk',
    'BWh',
    'BWk',
    'Cfa',
    'Cfb',
    'Cfc',
    'Csa',
    'Csb',
    'Csc',
    'Cwa',
    'Cwb',
    'Cwc',
    'Dfa',
    'Dfb',
    'Dfc',
    'Dfd',
    'Dsa',
    'Dsb',
    'Dsc',
    'Dwa',
    'Dwb',
    'Dwc',
    'Dwd',
    'EF',
    'ET',
];

const CLASS_TO_INDEX = Object.fromEntries(KOPPEN_CLASSES.map((code, index) => [code, index + 1]));

const CSV_URL =
    'https://raw.githubusercontent.com/andreigec/koppen-climate-lookup/main/src/koppen.csv';

function snapLat(lat) {
    return Math.round((lat + 0.25) / 0.5) * 0.5 - 0.25;
}

function snapLng(lng) {
    return Math.round((lng + 179.75) / 0.5) * 0.5 - 179.75;
}

function gridKey(lat, lng) {
    return `${lat.toFixed(6)},${lng.toFixed(6)}`;
}

async function loadCsvGrid() {
    const response = await fetch(CSV_URL);

    if (!response.ok) {
        throw new Error(`Failed to download Köppen CSV (${response.status})`);
    }

    const text = await response.text();
    const grid = new Map();

    for (const line of text.trim().split('\n').slice(1)) {
        const trimmed = line.trim();

        if (!trimmed) {
            continue;
        }

        const [lat, lng, code] = trimmed.split(',');

        if (!lat || !lng || !code) {
            continue;
        }

        const index = CLASS_TO_INDEX[code];

        if (!index) {
            throw new Error(`Unknown Köppen class in CSV: ${code}`);
        }

        grid.set(gridKey(Number(lat), Number(lng)), index);
    }

    return grid;
}

function sampleHalfDegree(grid, lat, lng) {
    return grid.get(gridKey(snapLat(lat), snapLng(lng))) ?? 0;
}

function majorityClass(grid, latCenter, lngCenter) {
    const votes = new Map();

    for (const dLat of [-0.25, 0.25]) {
        for (const dLng of [-0.25, 0.25]) {
            const index = sampleHalfDegree(grid, latCenter + dLat, lngCenter + dLng);

            if (index === 0) {
                continue;
            }

            votes.set(index, (votes.get(index) ?? 0) + 1);
        }
    }

    let winner = 0;
    let winnerVotes = 0;

    for (const [index, count] of votes) {
        if (count > winnerVotes) {
            winner = index;
            winnerVotes = count;
        }
    }

    return winner;
}

const grid = await loadCsvGrid();
const bytes = new Uint8Array(WIDTH * HEIGHT);

for (let row = 0; row < HEIGHT; row++) {
    const latCenter = 90 - (row + 0.5) * (180 / HEIGHT);

    for (let col = 0; col < WIDTH; col++) {
        const lngCenter = -180 + (col + 0.5) * (360 / WIDTH);
        bytes[row * WIDTH + col] = majorityClass(grid, latCenter, lngCenter);
    }
}

let binary = '';

for (let i = 0; i < bytes.length; i++) {
    binary += String.fromCharCode(bytes[i]);
}

const encoded = Buffer.from(binary, 'binary').toString('base64');

const classList = KOPPEN_CLASSES.map((code) => `'${code}'`).join(', ');

const contents = `// Generated by scripts/generate-koppen-mask.mjs. Do not edit by hand.
// 1-degree Köppen-Geiger class indices downsampled from Beck et al. (2018)
// present-day 0.5° land raster (Beck_KG_V1_present_0p5.tif). Index 0 is ocean
// or no land sample. See KOPPEN_CLASSES for code names.
// Cite: Beck, H.E. et al., Sci. Data 5, 180214 (2018).
export const KOPPEN_WIDTH = ${WIDTH};
export const KOPPEN_HEIGHT = ${HEIGHT};
export const KOPPEN_CLASSES = [${classList}];
export const KOPPEN_MASK_BASE64 =
    '${encoded}';
`;

writeFileSync(outputPath, contents);

console.log(`Wrote ${outputPath} (${WIDTH}x${HEIGHT}, ${encoded.length} base64 chars)`);
